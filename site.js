// alt: 雪の日の代わりの道（NAV の alt）。無ければふだんの道
function navLeg(d,i,alt){ var n=NAV[d+'-'+i]||{}; return (alt&&n.alt)?n.alt:n; }
function openNav(d,i,alt){
  var web=navUrl(d,i,alt);
  if(/iPhone|iPad|iPod/.test(navigator.userAgent)){
    var t=Date.now(); location.href=navApp(d,i,alt);
    setTimeout(function(){ if(!document.hidden && Date.now()-t<2500) window.open(web,'_blank'); },1500);
  } else window.open(web,'_blank');
}
// 出発地は今いる場所（Google マップが決める）。経由地を入れて、想定の道を外れないようにする
function navUrl(d,i,alt){
  var m=DAYS[d].m[i], n=navLeg(d,i,alt);
  return 'https://www.google.com/maps/dir/?api=1&travelmode=driving&dir_action=navigate&destination='+m.ll.join(',')+
    (n.via&&n.via.length?'&waypoints='+n.via.map(function(p){ return p.join(','); }).join('%7C'):'');
}

