// その日が休みか
function siteClosed(n,date){
  var c=(SITE_INFO[n]||{}).closed; if(!c) return false;
  var dow=date.getDay(), dd=date.getDate(), md=('0'+(date.getMonth()+1)).slice(-2)+'-'+('0'+dd).slice(-2);
  if((c.dow||[]).indexOf(dow)>=0) return true;
  if((c.nth||[]).some(function(x){ return x[1]===dow && Math.ceil(dd/7)===x[0]; })) return true;
  if((c.span||[]).some(function(s){ return s[0]<=s[1] ? (md>=s[0]&&md<=s[1]) : (md>=s[0]||md<=s[1]); })) return true;
  return false;
}
// 着く時刻が締め切りを過ぎるか（分で比べる）
function siteLate(n,arriveAt){
  var l=(SITE_INFO[n]||{}).last; if(!l) return false;
  var p=l.split(':'), lim=(+p[0])*60+(+p[1]);
  return arriveAt.getHours()*60+arriveAt.getMinutes()>lim;
}

