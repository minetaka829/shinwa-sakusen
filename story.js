// 語りの部品: 文字列、または {t, ask, ans, wait}（ask のあと wait 秒だまって待ってから ans）
function partTexts(p){ return typeof p==='string'?[p]:[p.t,p.ask,p.ans].filter(Boolean); }
function voiceLines(){
  var boss=[], enemy=[], i;
  function B(t){ if(t) boss.push(t); }
  function P(p){ partTexts(p).forEach(B); }
  DAYS.forEach(function(d,di){
    B(d.open); (d.talk||[]).forEach(B);
    d.m.forEach(function(m,mi){ B(m.ap); B(m.os+LINES.mission+m.ms); B(LINES.next(m.n)); B(LINES.skipTo(m.n)); var p=(POSE[di]||[])[mi]; if(p) B(LINES.pose+p); });
    (MYTH[di]||[]).forEach(P);
    (SCENE[di]||[]).forEach(function(x){ partTexts(x).forEach(function(t){ (x.who==='enemy'?enemy:boss).push(t); }); });
    (SECRET[di]||[]).forEach(P);
    (ENEMY[di]||[]).forEach(function(x){
      enemy.push(x.t); B(x.reply);
      (x.more||[]).forEach(function(m){ partTexts(m).forEach(function(t){ (m.who==='enemy'?enemy:boss).push(t); }); });
    });
    var r=(window.ROUTE||{})[di]||{};
    (r.trivia||[]).forEach(B);
    (r.road||[]).forEach(function(x){B(x.t);}); (r.caution||[]).forEach(function(x){B(x.t);});
    (r.hidden||[]).forEach(function(x){B(LINES.hidden+x.t);}); (r.detour||[]).forEach(function(x){B(LINES.detour+x.t);});
    var rc=RECAP[di]||{}; [].concat(rc.secret||[]).forEach(B); B(rc.next);
  });
  Object.keys(LINES).forEach(function(k){ if(typeof LINES[k]==='string') B(LINES[k]); });
  for(i=10;i<=600;i+=10) B(LINES.recapKm(i));
  for(i=0;i<=12;i++) B(LINES.recapDone(i));
  for(i=0;i<=41;i++) B(LINES.recapPhoto(i));
  Object.keys(TIME).forEach(function(k){B(TIME[k]);});
  GOURMET_REPLY.forEach(B); PHOTO_REPLY.forEach(B); B(BRIEF); B(ENDING);
  enemy.push(ENDING_EXTRA.t); B(ENDING_EXTRA.reply);
  return {boss:boss, enemy:enemy};
}
